package com.zenith.glyphstudio.data

/** Preset categories. Names carry a short prefix so they stay grouped anywhere they're listed. */
enum class PresetCategory(val prefix: String, val title: String) {
    HERO("HERO", "Hero Icons"),
    WEAPON("WPN", "Weapons"),
    MOOD("MOOD", "Moods"),
    MINE("MY", "My Designs"),
}

/** Built-in pixel art (fan-made, hero-inspired). '#' = full, '+' = dim, '.' = off. Generated from scratchpad art.py. */
object BuiltInPresets {
    private fun art(rows: String): GlyphFrame {
        val lines = rows.trim('\n').lines()
        require(lines.size == GRID && lines.all { it.length == GRID })
        return GlyphFrame.of(IntArray(CELLS) { i ->
            when (lines[i / GRID][i % GRID]) { '#' -> 255; '+' -> 90; else -> 0 }
        })
    }

    private fun preset(cat: PresetCategory, name: String, fps: Int, vararg frames: String) =
        GlyphAnimation(id = "builtin_${cat.name}_${name.filter(Char::isLetterOrDigit)}",
            name = "${cat.prefix} · $name", frames = frames.map(::art), fps = fps)

