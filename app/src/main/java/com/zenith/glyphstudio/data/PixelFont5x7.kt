    const val W = 5
    const val H = 7

    private val glyphs: Map<Char, IntArray> = mapOf(
        'A' to r(0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11), 'B' to r(0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E),
