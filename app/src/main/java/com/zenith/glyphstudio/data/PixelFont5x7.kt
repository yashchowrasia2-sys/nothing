        '@' to r(0x0E, 0x11, 0x17, 0x15, 0x17, 0x10, 0x0F), '\'' to r(0x04, 0x04, 0x08, 0, 0, 0, 0),
        '<' to r(0x02, 0x04, 0x08, 0x10, 0x08, 0x04, 0x02), '>' to r(0x08, 0x04, 0x02, 0x01, 0x02, 0x04, 0x08),
        '♥' to r(0, 0x0A, 0x1F, 0x1F, 0x0E, 0x04, 0),
    )

    private fun r(vararg rows: Int) = rows

    fun glyph(c: Char): IntArray = glyphs[c.uppercaseChar()] ?: glyphs['?']!!

    /** Text → column bitmap (each column = 7-bit mask, bit 0 = top row), 1px spacing. */
    fun columns(text: String): List<Int> {
        val cols = ArrayList<Int>()
        text.forEach { ch ->
            val g = glyph(ch)
            for (x in 0 until W) {
                var col = 0
                for (y in 0 until H) if (g[y] and (0x10 shr x) != 0) col = col or (1 shl y)
                cols += col
            }
            cols += 0
        }
        return cols
    }
}

/** Compact 3x5 digits for HUD centre readouts (row bits: 0x4 = left). */
object PixelFont3x5 {
    private val d = arrayOf(
        intArrayOf(7, 5, 5, 5, 7), intArrayOf(2, 6, 2, 2, 7), intArrayOf(7, 1, 7, 4, 7), intArrayOf(7, 1, 7, 1, 7),
        intArrayOf(5, 5, 7, 1, 1), intArrayOf(7, 4, 7, 1, 7), intArrayOf(7, 4, 7, 5, 7), intArrayOf(7, 1, 1, 1, 1),
        intArrayOf(7, 5, 7, 5, 7), intArrayOf(7, 5, 7, 1, 7),
    )

    fun draw(frame: IntArray, digit: Int, ox: Int, oy: Int, level: Int) {
        val g = d[digit.coerceIn(0, 9)]
        for (y in 0 until 5) for (x in 0 until 3) if (g[y] and (4 shr x) != 0) {
            val px = ox + x; val py = oy + y
            if (px in 0 until GRID && py in 0 until GRID) frame[py * GRID + px] = level
        }
    }

    /** Draws a 1–2 digit number centred in the 13x13 grid. */
    fun drawNumber(frame: IntArray, n: Int, level: Int) {
        val v = n.coerceIn(0, 99)
        if (v < 10) draw(frame, v, 5, 4, level)
        else { draw(frame, v / 10, 3, 4, level); draw(frame, v % 10, 7, 4, level) }
    }
}
