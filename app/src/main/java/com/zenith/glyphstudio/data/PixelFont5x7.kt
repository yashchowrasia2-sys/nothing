        'O' to r(0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E), 'P' to r(0x1E, 0x11, 0x11, 0x1E, 0x10, 0x10, 0x10),
        'Q' to r(0x0E, 0x11, 0x11, 0x11, 0x15, 0x12, 0x0D), 'R' to r(0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11),
