        ' ' to r(0, 0, 0, 0, 0, 0, 0), '!' to r(0x04, 0x04, 0x04, 0x04, 0x04, 0x00, 0x04),
        '?' to r(0x0E, 0x11, 0x01, 0x02, 0x04, 0x00, 0x04), '.' to r(0, 0, 0, 0, 0, 0x0C, 0x0C),
